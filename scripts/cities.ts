#!/usr/bin/env node

import { calculateMunicipalityCheckDigit } from "../src/_internals/calculate-municipality-check-digit/calculate-municipality-check-digit.ts";
import { DATA as STATES } from "../src/_internals/constants/states.ts";
import { fetchWithRetry } from "../src/_internals/fetch-with-retry/fetch-with-retry.ts";
import { runAsEntryPoint, serializeTexts, writeGeneratedFiles } from "./lookup-table.ts";

const STATE_CODES = STATES.map((state) => state.code);

type City = {
	id: number;
	nome: string;
	microrregiao: {
		id: number;
		nome: string;
		mesorregiao: {
			id: number;
			nome: string;
			UF: {
				id: number;
				sigla: string;
				nome: string;
				regiao: {
					id: number;
					sigla: string;
					nome: string;
				};
			};
		};
	} | null;
	"regiao-imediata": {
		id: number;
		nome: string;
		"regiao-intermediaria": {
			id: number;
			nome: string;
			UF: {
				id: number;
				sigla: string;
				nome: string;
			};
		};
	};
};

const isCity = (value: unknown): value is City =>
	typeof value === "object" &&
	value !== null &&
	"id" in value &&
	typeof value.id === "number" &&
	"nome" in value &&
	typeof value.nome === "string" &&
	"microrregiao" in value &&
	"regiao-imediata" in value;

/**
 * Packs the codes of one state, in the order of its municipality names, as the text
 * `readMunicipalityCodes` reads: the first 6 digits of each code as its difference from the one
 * before it (the first from zero), in base 36 and separated by commas. The seventh digit is not
 * written when it is the check digit `calculateMunicipalityCheckDigit` gives, and follows a dot when it is not.
 * @param {string[]} codes - The 7 digit codes of the state.
 * @returns {string} The packed codes.
 */
const packMunicipalityCodes = (codes: readonly string[]): string => {
	let previous = 0;

	return codes
		.map((code) => {
			if (!/^\d{7}$/.test(code)) throw new Error(`municipality code ${code} is not 7 digits`);

			const value = Number(code.slice(0, 6));
			const difference = (value - previous).toString(36);

			previous = value;

			return Number(code[6]) === calculateMunicipalityCheckDigit(code.slice(0, 6))
				? difference
				: `${difference}.${code[6]}`;
		})
		.join(",");
};

const continued = (parts: readonly string[], separator: string): string => {
	const continuation = "\\\n";
	const joined = parts.join(`${separator}${continuation}`);

	return `"${joined}"`;
};

/**
 * Renders the modules the municipalities are shipped as: for each state, its names packed by
 * `packTexts` and its codes packed by `packMunicipalityCodes`, both in the order of the names,
 * which are sorted with `localeCompare` in the "pt-BR" locale.
 * @param {Record<string, [string, string][]>} byState - The `[name, ibgeCode]` pairs of each state.
 * @returns {Record<string, string>} The content of the generated files, by their paths.
 */
export const renderMunicipalities = (
	byState: Record<string, [string, string][]>,
): Record<string, string> => {
	const states = Object.keys(byState).sort((a, b) => a.localeCompare(b));
	const sorted = (state: string): [string, string][] =>
		[...(byState[state] ?? [])].sort(([a], [b]) => a.localeCompare(b, "pt-BR"));

	const names = states.map(
		(state) => `\t${state}: ${serializeTexts(sorted(state).map(([name]) => name))},`,
	);
	const codes = states.map((state) => {
		const packed = packMunicipalityCodes(sorted(state).map(([, code]) => code));

		return `\t${state}: ${continued(packed.split(","), ",")},`;
	});

	return {
		"./src/_internals/constants/municipality-names.ts": `import { type StateCode } from "./states";

/**
 * The name of every Brazilian municipality, published by the IBGE, for each state: the names
 * packed by \`packTexts\` (scripts/lookup-table.ts), which \`unpackTexts\` reads, sorted with
 * \`localeCompare\` in the "pt-BR" locale. The code of the n-th name
 * is the n-th of \`MUNICIPALITY_CODES\` (\`municipality-codes.ts\`), a module of its own so that
 * reading the codes does not bundle the names.
 *
 * Generated by \`node ./scripts/cities.ts\`. Do not edit by hand.
 *
 * @see Official: https://servicodados.ibge.gov.br/api/docs/localidades
 */
export const MUNICIPALITY_NAMES: Record<StateCode, string> = {
${names.join("\n")}
};
`,
		"./src/_internals/constants/municipality-codes.ts": `import { type StateCode } from "./states";

/**
 * The IBGE code of every Brazilian municipality, for each state, in the order of the names of
 * \`MUNICIPALITY_NAMES\` (\`municipality-names.ts\`). The first 6 digits of each code are written as
 * their difference from the one before it (the first from zero) in base 36, separated by commas,
 * and the seventh digit, the check digit, is left out unless it breaks the rule \`readMunicipalityCodes\`
 * derives it with: it then follows a dot. Each entry sits on a line of its own, ended by a line
 * continuation that adds nothing to the value, so a refresh diffs to the codes that changed.
 *
 * Generated by \`node ./scripts/cities.ts\`. Do not edit by hand.
 *
 * @see Official: https://servicodados.ibge.gov.br/api/docs/localidades
 */
export const MUNICIPALITY_CODES: Record<StateCode, string> = {
${codes.join("\n")}
};
`,
	};
};

const main = async (): Promise<void> => {
	const response = await fetchWithRetry(
		"https://servicodados.ibge.gov.br/api/v1/localidades/municipios",
	);

	if (!response.ok) {
		throw new Error(`IBGE municipalities request failed with status ${response.status}`);
	}

	const json: unknown = await response.json();

	if (!Array.isArray(json) || !json.every((entry) => isCity(entry))) {
		throw new Error("IBGE municipalities payload is not an array of city entries");
	}

	const byState: Record<string, [string, string][]> = {};

	for (const city of json) {
		const stateInitials =
			city.microrregiao?.mesorregiao?.UF?.sigla ??
			city["regiao-imediata"]?.["regiao-intermediaria"]?.UF?.sigla;

		if (stateInitials === undefined || stateInitials === "") continue;

		byState[stateInitials] ??= [];
		byState[stateInitials].push([city.nome, String(city.id)]);
	}

	const missingStates = STATE_CODES.filter((code) => !Object.hasOwn(byState, code));

	if (missingStates.length > 0) {
		throw new Error(`IBGE response is missing municipalities for: ${missingStates.join(", ")}`);
	}

	await writeGeneratedFiles(renderMunicipalities(byState));
};

await runAsEntryPoint(import.meta.filename, main);
